const RTL = { fa: true, ps: true };
const metaDesc = document.querySelector('meta[name="description"]');

function setLang(code) {
  const dict = I18N[code] || I18N.en;
  document.documentElement.lang = code;
  document.documentElement.dir = RTL[code] ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-i18n]').forEach(el => { const v = dict[el.dataset.i18n]; if (v) el.textContent = v; });
  document.querySelectorAll('[data-i18n-html]').forEach(el => { const v = dict[el.dataset.i18nHtml]; if (v) el.innerHTML = v; });
  document.title = dict.title;
  if (metaDesc) metaDesc.setAttribute('content', dict.desc);
  document.querySelectorAll('.lang button').forEach(b => b.setAttribute('aria-pressed', String(b.dataset.lang === code)));
  try { localStorage.setItem('partaw-lang', code); } catch (e) {}
}

document.querySelectorAll('.lang button').forEach(b => b.addEventListener('click', () => setLang(b.dataset.lang)));

let saved = 'en';
try { saved = localStorage.getItem('partaw-lang') || 'en'; } catch (e) {}
setLang(I18N[saved] ? saved : 'en');

/* Intro: remove from the page once it has faded out */
const intro = document.getElementById('intro');
if (intro) intro.addEventListener('animationend', e => { if (e.animationName === 'introOut') intro.classList.add('gone'); });

/* Mobile menu */
const toggle = document.querySelector('.menu-toggle');
const nav = document.getElementById('nav');
if (toggle && nav) {
  toggle.addEventListener('click', () => {
    const open = nav.classList.toggle('open');
    toggle.setAttribute('aria-expanded', String(open));
  });
  nav.querySelectorAll('a').forEach(a => a.addEventListener('click', () => {
    nav.classList.remove('open');
    toggle.setAttribute('aria-expanded', 'false');
  }));
}

/* Footer year */
const year = document.getElementById('year');
if (year) year.textContent = new Date().getFullYear();

/* Active nav link while scrolling */
if ('IntersectionObserver' in window) {
  const links = [...document.querySelectorAll('.nav a')];
  const spy = new IntersectionObserver(entries => entries.forEach(entry => {
    if (entry.isIntersecting) links.forEach(a => a.classList.toggle('active', a.getAttribute('href') === '#' + entry.target.id));
  }), { rootMargin: '-45% 0px -50% 0px' });
  document.querySelectorAll('main section[id]').forEach(s => spy.observe(s));
}

/* 3D pointer interaction (desktop only, respects reduced motion) */
const reduce = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
const fine = window.matchMedia('(pointer: fine)').matches;
if (!reduce && fine) {
  const stage = document.getElementById('stage');
  const emblem = document.getElementById('emblem');
  if (stage && emblem) {
    stage.addEventListener('pointermove', e => {
      const r = stage.getBoundingClientRect();
      const x = (e.clientX - r.left) / r.width - .5;
      const y = (e.clientY - r.top) / r.height - .5;
      emblem.style.setProperty('--ry', (x * 26) + 'deg');
      emblem.style.setProperty('--rx', (-y * 22) + 'deg');
    });
    stage.addEventListener('pointerleave', () => {
      emblem.style.setProperty('--ry', '0deg');
      emblem.style.setProperty('--rx', '0deg');
    });
  }
  document.querySelectorAll('.tilt').forEach(card => {
    card.addEventListener('pointermove', e => {
      const r = card.getBoundingClientRect();
      const x = (e.clientX - r.left) / r.width;
      const y = (e.clientY - r.top) / r.height;
      card.style.setProperty('--mx', (x * 100) + '%');
      card.style.setProperty('--my', (y * 100) + '%');
      card.style.transform = `perspective(900px) rotateX(${(.5 - y) * 6}deg) rotateY(${(x - .5) * 8}deg) translateY(-4px)`;
    });
    card.addEventListener('pointerleave', () => { card.style.transform = ''; });
  });
}
